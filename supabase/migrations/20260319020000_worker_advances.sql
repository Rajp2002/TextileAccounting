-- ============================================================
-- MIGRATION: Worker Advances (Upaad) Table
-- ============================================================
-- Tracks micro-loans given to workers. These are deducted during
-- the monthly payroll settlement cycle. Supports both piece-rate
-- (workers) and fixed/salaried (fixed_workers) via polymorphic FKs.
-- ============================================================

-- 1. Create the worker_advances table
CREATE TABLE IF NOT EXISTS worker_advances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id UUID REFERENCES organizations(id) NOT NULL,

    -- Polymorphic FK (same pattern as payroll_payments)
    meter_worker_id BIGINT REFERENCES workers(id) ON DELETE SET NULL,
    fixed_worker_id BIGINT REFERENCES fixed_workers(id) ON DELETE SET NULL,

    amount DECIMAL NOT NULL CHECK (amount > 0),
    description TEXT,                          -- e.g. "Medicine", "Home travel", "Rent"

    status TEXT NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'deducted')),

    -- Audit trail: links to the payroll_payments record that settled this advance
    settled_by_payment_id BIGINT REFERENCES payroll_payments(id) ON DELETE SET NULL,

    deducted_at TIMESTAMPTZ,                   -- when it was settled
    deducted_in_month TEXT,                    -- which payroll month (YYYY-MM)

    created_at TIMESTAMPTZ DEFAULT now(),

    -- Exactly one FK must be set
    CONSTRAINT advance_exactly_one_worker_fk CHECK (
        (meter_worker_id IS NOT NULL AND fixed_worker_id IS NULL) OR
        (meter_worker_id IS NULL AND fixed_worker_id IS NOT NULL)
    )
);

-- 2. Indexes for fast lookups during settlement
CREATE INDEX IF NOT EXISTS idx_advances_meter_worker_pending
    ON worker_advances (org_id, meter_worker_id, status)
    WHERE meter_worker_id IS NOT NULL AND status = 'pending';

CREATE INDEX IF NOT EXISTS idx_advances_fixed_worker_pending
    ON worker_advances (org_id, fixed_worker_id, status)
    WHERE fixed_worker_id IS NOT NULL AND status = 'pending';

-- 3. Enable RLS
ALTER TABLE worker_advances ENABLE ROW LEVEL SECURITY;

-- 4. RLS Policies (JWT pattern — matches optimize_rls_with_jwt migration)

-- SELECT: Everyone in org can view (supervisors get view-only access)
CREATE POLICY "Tenant Isolation" ON worker_advances
    FOR SELECT
    USING (org_id = (auth.jwt() ->> 'org_id')::uuid);

-- INSERT: Owner-only
CREATE POLICY "Owners Create Advances" ON worker_advances
    FOR INSERT
    WITH CHECK (
        (auth.jwt() ->> 'user_role') = 'owner' AND
        org_id = (auth.jwt() ->> 'org_id')::uuid
    );

-- UPDATE: Owner-only (for marking as deducted during settlement)
CREATE POLICY "Owners Update Advances" ON worker_advances
    FOR UPDATE
    USING (
        (auth.jwt() ->> 'user_role') = 'owner' AND
        org_id = (auth.jwt() ->> 'org_id')::uuid
    );

-- DELETE: Owner-only (for removing pending advances)
CREATE POLICY "Owners Delete Advances" ON worker_advances
    FOR DELETE
    USING (
        (auth.jwt() ->> 'user_role') = 'owner' AND
        org_id = (auth.jwt() ->> 'org_id')::uuid
    );
