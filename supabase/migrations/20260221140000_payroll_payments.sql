-- Monthly Payroll Payments tracker
-- Stores a snapshot of what was owed + paid status per worker per month.

CREATE TABLE IF NOT EXISTS payroll_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id UUID REFERENCES organizations(id) NOT NULL,
    worker_type TEXT NOT NULL CHECK (worker_type IN ('meter', 'fixed')),
    worker_id BIGINT NOT NULL,  -- references workers.id OR fixed_workers.id
    month TEXT NOT NULL,        -- YYYY-MM e.g. '2026-02'
    amount DECIMAL NOT NULL DEFAULT 0,
    paid BOOLEAN DEFAULT false,
    paid_at TIMESTAMPTZ,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE(org_id, worker_type, worker_id, month)
);

ALTER TABLE payroll_payments ENABLE ROW LEVEL SECURITY;

-- Everyone in org can view
CREATE POLICY "Tenant Isolation" ON payroll_payments
    FOR SELECT
    USING (org_id = (SELECT org_id FROM profiles WHERE id = auth.uid()));

-- Only owners can insert/update/delete
CREATE POLICY "Owners Manage Payroll" ON payroll_payments
    FOR ALL
    USING (
        (SELECT role FROM profiles WHERE id = auth.uid()) = 'owner' AND
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );
