-- Create organizations table
CREATE TABLE IF NOT EXISTS organizations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT now(),
    owner_id UUID NOT NULL REFERENCES auth.users(id)
);

-- Create profiles table
CREATE TABLE IF NOT EXISTS profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id),
    org_id UUID REFERENCES organizations(id),
    role TEXT CHECK (role IN ('owner', 'supervisor')),
    full_name TEXT,
    phone TEXT
);

-- Create workers table
CREATE TABLE IF NOT EXISTS workers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id UUID REFERENCES organizations(id),
    name TEXT NOT NULL,
    rate_per_meter DECIMAL,
    is_active BOOLEAN DEFAULT true
);

-- Create machines table (was missing from original migration — F-4/F-5 fix)
CREATE TABLE IF NOT EXISTS machines (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    org_id UUID REFERENCES organizations(id) NOT NULL,
    name TEXT NOT NULL,
    status TEXT DEFAULT 'active',
    created_at TIMESTAMPTZ DEFAULT now()
);

-- Create production_logs table
CREATE TABLE IF NOT EXISTS production_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id UUID REFERENCES organizations(id),
    worker_id BIGINT REFERENCES workers(id),
    machine_id UUID REFERENCES machines(id),
    meters DECIMAL NOT NULL,
    date DATE DEFAULT CURRENT_DATE,
    created_by UUID REFERENCES profiles(id)
);

-- ============================================================
-- Enable Row Level Security (RLS)
-- ============================================================
ALTER TABLE organizations ENABLE ROW LEVEL SECURITY;
ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE workers ENABLE ROW LEVEL SECURITY;
ALTER TABLE machines ENABLE ROW LEVEL SECURITY;
ALTER TABLE production_logs ENABLE ROW LEVEL SECURITY;

-- ============================================================
-- RLS POLICIES
-- ============================================================

-- ============================================================
-- ORGANIZATIONS
-- ============================================================

-- SELECT: Members can view their own organization
CREATE POLICY "Tenant Isolation" ON organizations
    FOR SELECT
    USING (id = (SELECT org_id FROM profiles WHERE id = auth.uid()));

-- INSERT: Any authenticated user can create an organization (during onboarding)
CREATE POLICY "Authenticated users can create organization" ON organizations
    FOR INSERT
    WITH CHECK (auth.uid() = owner_id);

-- UPDATE: Only the org owner can update organization details
CREATE POLICY "Owner can update organization" ON organizations
    FOR UPDATE
    USING (owner_id = auth.uid());

-- ============================================================
-- PROFILES
-- ============================================================

-- SELECT: Members can view profiles within their organization
CREATE POLICY "Tenant Isolation" ON profiles
    FOR SELECT
    USING (
        id = auth.uid() OR
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );

-- INSERT: Users can create their own profile (during sign-up)
CREATE POLICY "Users can insert their own profile" ON profiles
    FOR INSERT
    WITH CHECK (auth.uid() = id);

-- UPDATE: Users can update their own profile
CREATE POLICY "Users can update their own profile" ON profiles
    FOR UPDATE
    USING (auth.uid() = id);

-- ============================================================
-- WORKERS
-- ============================================================

-- SELECT: Members can view workers in their org
CREATE POLICY "Tenant Isolation" ON workers
    FOR SELECT
    USING (org_id = (SELECT org_id FROM profiles WHERE id = auth.uid()));

-- ALL (Insert/Update/Delete): Only owners can manage workers
CREATE POLICY "Owners Manage Workers" ON workers
    FOR ALL
    USING (
        (SELECT role FROM profiles WHERE id = auth.uid()) = 'owner' AND
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );

-- ============================================================
-- MACHINES (F-4 fix: full RLS coverage)
-- ============================================================

-- SELECT: Members can view machines in their org
CREATE POLICY "Tenant Isolation" ON machines
    FOR SELECT
    USING (org_id = (SELECT org_id FROM profiles WHERE id = auth.uid()));

-- ALL (Insert/Update/Delete): Only owners can manage machines
CREATE POLICY "Owners Manage Machines" ON machines
    FOR ALL
    USING (
        (SELECT role FROM profiles WHERE id = auth.uid()) = 'owner' AND
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );

-- ============================================================
-- PRODUCTION LOGS
-- ============================================================

-- SELECT: Everyone in the org can view logs
CREATE POLICY "Tenant Isolation Select" ON production_logs
    FOR SELECT
    USING (org_id = (SELECT org_id FROM profiles WHERE id = auth.uid()));

-- INSERT: Supervisors and Owners can insert logs
CREATE POLICY "Supervisor/Owner Insert" ON production_logs
    FOR INSERT
    WITH CHECK (
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );

-- UPDATE: Only Owners can update logs
CREATE POLICY "Owner Update" ON production_logs
    FOR UPDATE
    USING (
        (SELECT role FROM profiles WHERE id = auth.uid()) = 'owner' AND
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );

-- DELETE: Only Owners can delete logs
CREATE POLICY "Owner Delete" ON production_logs
    FOR DELETE
    USING (
        (SELECT role FROM profiles WHERE id = auth.uid()) = 'owner' AND
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );
