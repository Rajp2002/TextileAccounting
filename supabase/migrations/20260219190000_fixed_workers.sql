-- Fixed Workers & Attendance
-- Adds support for fixed-salary staff (master, supervisor, helper, mender, sanitation, daily)
-- and attendance tracking for day-to-day workers.

-- 1. Fixed Workers table
CREATE TABLE IF NOT EXISTS fixed_workers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id UUID REFERENCES organizations(id) NOT NULL,
    name TEXT NOT NULL,
    role TEXT NOT NULL CHECK (role IN ('master', 'supervisor', 'helper', 'mender', 'sanitation', 'daily')),
    monthly_salary DECIMAL NOT NULL DEFAULT 0,
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. Attendance table (for day-to-day workers)
CREATE TABLE IF NOT EXISTS attendance (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id UUID REFERENCES organizations(id) NOT NULL,
    fixed_worker_id BIGINT REFERENCES fixed_workers(id) ON DELETE CASCADE NOT NULL,
    date DATE NOT NULL,
    present BOOLEAN DEFAULT true,
    marked_by UUID REFERENCES profiles(id),
    created_at TIMESTAMPTZ DEFAULT now(),
    UNIQUE(fixed_worker_id, date)
);

-- 3. RLS
ALTER TABLE fixed_workers ENABLE ROW LEVEL SECURITY;
ALTER TABLE attendance ENABLE ROW LEVEL SECURITY;

-- fixed_workers: Everyone in org can view
CREATE POLICY "Tenant Isolation" ON fixed_workers
    FOR SELECT
    USING (org_id = (SELECT org_id FROM profiles WHERE id = auth.uid()));

-- fixed_workers: Only owners can manage
CREATE POLICY "Owners Manage Fixed Workers" ON fixed_workers
    FOR ALL
    USING (
        (SELECT role FROM profiles WHERE id = auth.uid()) = 'owner' AND
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );

-- attendance: Everyone in org can view
CREATE POLICY "Tenant Isolation" ON attendance
    FOR SELECT
    USING (org_id = (SELECT org_id FROM profiles WHERE id = auth.uid()));

-- attendance: Supervisors and Owners can insert
CREATE POLICY "Supervisor/Owner Insert Attendance" ON attendance
    FOR INSERT
    WITH CHECK (
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );

-- attendance: Supervisors and Owners can update
CREATE POLICY "Supervisor/Owner Update Attendance" ON attendance
    FOR UPDATE
    USING (
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );

-- attendance: Only owners can delete
CREATE POLICY "Owner Delete Attendance" ON attendance
    FOR DELETE
    USING (
        (SELECT role FROM profiles WHERE id = auth.uid()) = 'owner' AND
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );
