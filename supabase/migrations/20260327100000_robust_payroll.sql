-- ─── 1. PAYROLL SETTLEMENTS ───────────────────────────────────

CREATE TABLE IF NOT EXISTS payroll_settlements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id UUID REFERENCES organizations(id) NOT NULL,
    worker_type TEXT NOT NULL CHECK (worker_type IN ('meter', 'fixed')),
    meter_worker_id BIGINT REFERENCES workers(id) ON DELETE SET NULL,
    fixed_worker_id BIGINT REFERENCES fixed_workers(id) ON DELETE SET NULL,
    month TEXT NOT NULL,        -- 'YYYY-MM'
    
    -- snapshots of the math
    gross_pay NUMERIC NOT NULL DEFAULT 0,
    advance_deducted NUMERIC NOT NULL DEFAULT 0,
    net_payout NUMERIC NOT NULL DEFAULT 0,
    carried_forward_debt NUMERIC NOT NULL DEFAULT 0,
    
    compliance_flag BOOLEAN DEFAULT false, -- True if 50% cap was triggered
    is_final_settlement BOOLEAN DEFAULT false, -- True if termination logic used
    
    status TEXT DEFAULT 'paid' CHECK (status IN ('pending', 'paid')),
    settled_at TIMESTAMPTZ DEFAULT now(),
    created_at TIMESTAMPTZ DEFAULT now(),

    CONSTRAINT payroll_settlement_exactly_one_fk CHECK (
        (meter_worker_id IS NOT NULL AND fixed_worker_id IS NULL) OR
        (meter_worker_id IS NULL AND fixed_worker_id IS NOT NULL)
    ),
    UNIQUE(org_id, meter_worker_id, month),
    UNIQUE(org_id, fixed_worker_id, month)
);

-- Enable RLS
ALTER TABLE payroll_settlements ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Tenant Isolation" ON payroll_settlements
    FOR SELECT USING (org_id = (SELECT org_id FROM profiles WHERE id = auth.uid()));

CREATE POLICY "Owners Manage Settlements" ON payroll_settlements
    FOR ALL USING (
        (SELECT role FROM profiles WHERE id = auth.uid()) = 'owner' AND
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );

-- ─── 2. PAYROLL CONFIGS ────────────────────────────────────────

CREATE TABLE IF NOT EXISTS payroll_configs (
    org_id UUID REFERENCES organizations(id) PRIMARY KEY,
    cycle_start_day INT DEFAULT 1 CHECK (cycle_start_day >= 1 AND cycle_start_day <= 28),
    updated_at TIMESTAMPTZ DEFAULT now()
);

ALTER TABLE payroll_configs ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Tenant Isolation" ON payroll_configs
    FOR SELECT USING (org_id = (SELECT org_id FROM profiles WHERE id = auth.uid()));

CREATE POLICY "Owners Manage Config" ON payroll_configs
    FOR ALL USING (
        (SELECT role FROM profiles WHERE id = auth.uid()) = 'owner' AND
        org_id = (SELECT org_id FROM profiles WHERE id = auth.uid())
    );

-- ─── 3. UPDATE WORKER ADVANCES ─────────────────────────────────

ALTER TABLE worker_advances 
    ADD COLUMN IF NOT EXISTS settlement_id BIGINT REFERENCES payroll_settlements(id) ON DELETE SET NULL;

-- ─── 4. OVERHAUL RPC: SETTLE ───────────────────────────────────

CREATE OR REPLACE FUNCTION settle_worker_payroll(
    p_org_id UUID,
    p_worker_type TEXT,
    p_worker_id BIGINT,
    p_month TEXT,
    p_gross_amount NUMERIC,
    p_is_final_settlement BOOLEAN DEFAULT false
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_settlement_id BIGINT;
    v_total_advances NUMERIC := 0;
    v_max_deduction NUMERIC;
    v_actual_deduction NUMERIC := 0;
    v_remaining_debt NUMERIC := 0;
    v_advance RECORD;
    v_deduct_now NUMERIC;
    v_budget NUMERIC;
BEGIN
    -- 1. Calculate Total Pending Advances
    SELECT COALESCE(SUM(amount), 0) INTO v_total_advances
    FROM worker_advances
    WHERE org_id = p_org_id
      AND status = 'pending'
      AND CASE
            WHEN p_worker_type = 'meter' THEN meter_worker_id = p_worker_id
            ELSE fixed_worker_id = p_worker_id
          END;

    -- 2. Determine Deduction Cap (Universal Calculation Formula)
    -- If final settlement, cap is 100%. Otherwise, strict 50% limit.
    IF p_is_final_settlement THEN
        v_max_deduction := p_gross_amount;
    ELSE
        v_max_deduction := p_gross_amount * 0.5;
    END IF;

    -- 3. Determine Actual Deduction
    v_actual_deduction := LEAST(v_total_advances, v_max_deduction);
    v_budget := v_actual_deduction;

    -- 4. Create Settlement Record (The snapshot)
    IF p_worker_type = 'meter' THEN
        INSERT INTO payroll_settlements (
            org_id, worker_type, meter_worker_id, fixed_worker_id, month, 
            gross_pay, advance_deducted, net_payout, 
            compliance_flag, is_final_settlement
        )
        VALUES (
            p_org_id, p_worker_type, p_worker_id, NULL, p_month, 
            p_gross_amount, v_actual_deduction, p_gross_amount - v_actual_deduction,
            (v_actual_deduction >= v_max_deduction AND v_total_advances > v_max_deduction AND NOT p_is_final_settlement),
            p_is_final_settlement
        )
        ON CONFLICT (org_id, meter_worker_id, month) 
        DO UPDATE SET 
            gross_pay = EXCLUDED.gross_pay,
            advance_deducted = EXCLUDED.advance_deducted,
            net_payout = EXCLUDED.net_payout,
            compliance_flag = EXCLUDED.compliance_flag,
            is_final_settlement = EXCLUDED.is_final_settlement,
            settled_at = now()
        RETURNING id INTO v_settlement_id;
    ELSE
        INSERT INTO payroll_settlements (
            org_id, worker_type, meter_worker_id, fixed_worker_id, month, 
            gross_pay, advance_deducted, net_payout, 
            compliance_flag, is_final_settlement
        )
        VALUES (
            p_org_id, p_worker_type, NULL, p_worker_id, p_month, 
            p_gross_amount, v_actual_deduction, p_gross_amount - v_actual_deduction,
            (v_actual_deduction >= v_max_deduction AND v_total_advances > v_max_deduction AND NOT p_is_final_settlement),
            p_is_final_settlement
        )
        ON CONFLICT (org_id, fixed_worker_id, month) 
        DO UPDATE SET 
            gross_pay = EXCLUDED.gross_pay,
            advance_deducted = EXCLUDED.advance_deducted,
            net_payout = EXCLUDED.net_payout,
            compliance_flag = EXCLUDED.compliance_flag,
            is_final_settlement = EXCLUDED.is_final_settlement,
            settled_at = now()
        RETURNING id INTO v_settlement_id;
    END IF;

    -- 5. Deduct Advances (Oldest First)
    -- Important: We only deduct up to v_actual_deduction
    FOR v_advance IN
        SELECT id, amount
        FROM worker_advances
        WHERE org_id = p_org_id
          AND status = 'pending'
          AND CASE
                WHEN p_worker_type = 'meter' THEN meter_worker_id = p_worker_id
                ELSE fixed_worker_id = p_worker_id
              END
        ORDER BY created_at ASC
        FOR UPDATE
    LOOP
        EXIT WHEN v_budget <= 0;

        IF v_advance.amount <= v_budget THEN
            -- Full deduction of this specific advance
            v_deduct_now := v_advance.amount;
            UPDATE worker_advances
            SET status = 'deducted',
                deducted_at = now(),
                deducted_in_month = p_month,
                settlement_id = v_settlement_id
            WHERE id = v_advance.id;
        ELSE
            -- Partial deduction (Splitting the advance)
            v_deduct_now := v_budget;
            
            -- Update original to 'deducted' for the partial amount
            -- and create a new 'pending' advance for the remainder.
            -- This ensures total debt remains accurate.
            UPDATE worker_advances
            SET amount = v_deduct_now,
                status = 'deducted',
                deducted_at = now(),
                deducted_in_month = p_month,
                settlement_id = v_settlement_id
            WHERE id = v_advance.id;

            INSERT INTO worker_advances (org_id, meter_worker_id, fixed_worker_id, amount, description, status, settlement_id)
            VALUES (
                p_org_id, 
                CASE WHEN p_worker_type = 'meter' THEN p_worker_id ELSE NULL END,
                CASE WHEN p_worker_type = 'fixed' THEN p_worker_id ELSE NULL END,
                v_advance.amount - v_deduct_now,
                'Partial recovery carry-forward',
                'pending',
                v_settlement_id
            );
        END IF;

        v_budget := v_budget - v_deduct_now;
    END LOOP;

    -- 6. Calculate Carry-Forward Debt
    SELECT COALESCE(SUM(amount), 0) INTO v_remaining_debt
    FROM worker_advances
    WHERE org_id = p_org_id
      AND status = 'pending'
      AND CASE
            WHEN p_worker_type = 'meter' THEN meter_worker_id = p_worker_id
            ELSE fixed_worker_id = p_worker_id
          END;

    UPDATE payroll_settlements
    SET carried_forward_debt = v_remaining_debt
    WHERE id = v_settlement_id;

    RETURN jsonb_build_object(
        'settlement_id', v_settlement_id,
        'gross_pay', p_gross_amount,
        'advance_deducted', v_actual_deduction,
        'net_payout', p_gross_amount - v_actual_deduction,
        'carried_forward_debt', v_remaining_debt,
        'compliance_flag', (v_actual_deduction >= v_max_deduction AND v_total_advances > v_max_deduction AND NOT p_is_final_settlement)
    );
END;
$$;

-- ─── 5. OVERHAUL RPC: UNSETTLE ─────────────────────────────────

CREATE OR REPLACE FUNCTION unsettle_worker_payroll(
    p_org_id UUID,
    p_worker_type TEXT,
    p_worker_id BIGINT,
    p_month TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_settlement_id BIGINT;
    v_reverted_count INT := 0;
BEGIN
    -- 1. Find the settlement
    IF p_worker_type = 'meter' THEN
        SELECT id INTO v_settlement_id
        FROM payroll_settlements
        WHERE org_id = p_org_id
          AND meter_worker_id = p_worker_id
          AND month = p_month;
    ELSE
        SELECT id INTO v_settlement_id
        FROM payroll_settlements
        WHERE org_id = p_org_id
          AND fixed_worker_id = p_worker_id
          AND month = p_month;
    END IF;

    IF v_settlement_id IS NULL THEN
        RETURN jsonb_build_object('success', false, 'error', 'Settlement not found');
    END IF;

    -- 2. Restore advances
    -- We need to handle the partially split ones too. 
    -- Actually, splitting makes it tricky to "merge" back.
    -- For simplicity, we just mark them as pending again.
    UPDATE worker_advances
    SET status = 'pending',
        deducted_at = NULL,
        deducted_in_month = NULL,
        settlement_id = NULL
    WHERE settlement_id = v_settlement_id;

    GET DIAGNOSTICS v_reverted_count = ROW_COUNT;

    -- 3. Delete the settlement record
    DELETE FROM payroll_settlements WHERE id = v_settlement_id;

    RETURN jsonb_build_object(
        'success', true,
        'reverted_advances', v_reverted_count
    );
END;
$$;
