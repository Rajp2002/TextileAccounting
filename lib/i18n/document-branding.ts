const COPY: Record<Language, BrandingCopy> = { en, hi, gu }

export function brandingText(language: Language | null | undefined, key: BrandingCopyKey) {
  return COPY[language === 'hi' || language === 'gu' ? language : 'en'][key]
}

const ERROR_KEYS = new Set<string>([
  'file_missing', 'file_too_large', 'unsupported_format', 'format_mismatch', 'image_unreadable',
  'image_too_small', 'image_too_large', 'image_animated', 'storage_failed', 'rate_limited',
  'save_failed', 'gstin_invalid', 'phone_invalid', 'email_invalid',
])

/** A server result code as a sentence; plan and lock codes reuse their screen copy. */
export function brandingErrorText(language: Language | null | undefined, code: string | null | undefined) {
  if (code === 'upgrade_required') return brandingText(language, 'upgradeBody')
  if (code === 'locked') return brandingText(language, 'lockedBody')
  if (code === 'trace_failed' || code === 'svg_rejected') return brandingText(language, 'traceFailed')
  if (code && ERROR_KEYS.has(code)) return brandingText(language, `error_${code}` as BrandingCopyKey)
  return brandingText(language, 'error_generic')
}

