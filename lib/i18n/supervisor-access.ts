export const supervisorCopy: Record<Language, Record<SupervisorTextKey, string>> = { en, hi, gu }

export function supervisorText(language: Language, key: SupervisorTextKey, values?: Record<string, string | number>): string {
    const template = supervisorCopy[language]?.[key] ?? en[key]
    if (!values) return template
    return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match))
}
