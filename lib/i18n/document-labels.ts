export const DOCUMENT_LABELS: Record<Language, DocumentLabels> = { en, hi, gu }

export function documentLabels(language: Language | undefined | null): DocumentLabels {
  return DOCUMENT_LABELS[language === 'hi' || language === 'gu' ? language : 'en']
}

/** Fill `{name}`-style slots; the values are inserted as given. */
export function fillLabel(template: string, values: Record<string, string | number>) {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => key in values ? String(values[key]) : match)
}
