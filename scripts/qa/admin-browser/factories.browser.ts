import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'

test.beforeEach(async ({ context }) => {
    await context.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' ? route.continue() : route.abort())
})
test('synthetic directory uses real filters, URL state, stable paging and count drilldowns', async ({ page }, info) => {
    await page.goto('/admin/factories?limit=3', { waitUntil: 'domcontentloaded' })
    await expect(page.getByText('Synthetic component fixtures — no authentication or production-data verification')).toBeVisible()
    await expect(page.getByText('32 matching factories')).toBeVisible()
    const view = page.getByRole('link', { name: 'View factory' }).filter({ visible: true })
    expect(await view.count()).toBe(3)
    const first = await view.evaluateAll(links => links.map(link => link.getAttribute('href')))
    await page.getByRole('link', { name: 'Next 3 factories' }).click()
    await expect(page).toHaveURL(/cursor=/)
    await expect(page.getByText('32 matching factories')).toBeVisible()
    const second = await page.getByRole('link', { name: 'View factory' }).filter({ visible: true }).evaluateAll(links => links.map(link => link.getAttribute('href')))
    expect(second.filter(link => first.includes(link))).toEqual([])
    await page.goto('/admin/factories?cohort=production&plan=free&limit=3', { waitUntil: 'domcontentloaded' })
    await expect(page.getByText('2 matching factories')).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'Search population reporting groups' }).getByRole('link', { name: 'Production 32' })).toBeVisible()
    await expect(page.getByRole('navigation', { name: 'Search population reporting groups' }).getByRole('link', { name: 'Unclassified 1' })).toHaveAttribute('href', /cohort=unclassified/)
    await expect(page.getByText('Cotton Free Shared QA').filter({ visible: true })).toBeVisible()
    await page.getByRole('navigation', { name: 'Search population reporting groups' }).getByRole('link', { name: 'Unclassified 1' }).click()
    await expect(page).toHaveURL(/cohort=unclassified/)
    expect(new URL(page.url()).searchParams.has('plan')).toBe(false)
    expect(new URL(page.url()).searchParams.has('cursor')).toBe(false)
    await expect(page.getByText('1 matching factory')).toBeVisible()
    await page.goto('/admin/factories?cohort=production&plan=free&limit=3', { waitUntil: 'domcontentloaded' })
    await page.getByLabel('Find a factory').fill('Saffron Weaving QA')
    await page.getByLabel('Effective access').focus()
    await page.keyboard.press('Enter')
    await page.getByRole('option', { name: 'All access', exact: true }).click()
    await page.getByRole('button', { name: 'Apply filters' }).click()
    await expect(page).toHaveURL(/search=Saffron\+Weaving\+QA/)
    await expect(page.getByText('1 matching factory')).toBeVisible()
    const productionGroup = page.getByRole('navigation', { name: 'Search population reporting groups' }).getByRole('link', { name: 'Production 1' })
    await expect(productionGroup).toHaveAttribute('href', /search=Saffron\+Weaving\+QA/)
    await expect(page.getByText('Verified paid lite term', { exact: false }).filter({ visible: true })).toBeVisible()
    const width = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, viewport: innerWidth }))
    expect(width.scroll).toBeLessThanOrEqual(width.viewport)
    await mkdir('output/playwright/admin-console/read-fixtures', { recursive: true })
    await page.screenshot({ path: `output/playwright/admin-console/read-fixtures/factories-${info.project.name}-synthetic.png`, fullPage: true })
})
test('synthetic detail exposes minimal context, shared account quota and explicit source states', async ({ page }, info) => {
    await page.goto('/admin/factories/00000000-0000-4000-8000-000000000002', { waitUntil: 'domcontentloaded' })
    await expect(page.getByRole('heading', { name: 'Cotton Free Shared QA', exact: true })).toBeVisible()
    await expect(page.getByText('Shared across 2 owner factory grants.', { exact: false })).toBeVisible()
    await expect(page.getByText('uses no new credit', { exact: false })).toBeVisible()
    await expect(page.getByRole('link', { name: 'Open support queue' })).toHaveAttribute('href', /orgId=/)
    await page.getByText('Source coverage', { exact: true }).click()
    await expect(page.getByText('No historical zero-fill or lapse score.', { exact: false })).toBeVisible()
    expect(await page.locator('input[type=password]').count()).toBe(0)
    const width = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, viewport: innerWidth }))
    expect(width.scroll).toBeLessThanOrEqual(width.viewport)
    await mkdir('output/playwright/admin-console/read-fixtures', { recursive: true })
    await page.screenshot({ path: `output/playwright/admin-console/read-fixtures/factory-detail-${info.project.name}-synthetic.png`, fullPage: true })
})
test('synthetic unknown and unavailable sources stay distinct from zero and Free', async ({ page }) => {
    await page.goto('/admin/factories?plan=unknown', { waitUntil: 'domcontentloaded' })
    await expect(page.getByText('1 matching factory')).toBeVisible()
    await expect(page.getByText('Unknown', { exact: true }).filter({ visible: true })).toBeVisible()
    await page.goto('/admin/factories?scenario=unavailable', { waitUntil: 'domcontentloaded' })
    await expect(page.getByRole('heading', { name: 'The directory could not be loaded' })).toBeVisible()
    await expect(page.getByText('no count has been assumed', { exact: false })).toBeVisible()
    await expect(page.getByText('0 matching factories')).toHaveCount(0)
})
