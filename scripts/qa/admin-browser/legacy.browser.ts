import { expect, test } from '@playwright/test'
test('retained read-only list filters and next page stay in the URL', async ({ page }, info) => {
    await page.goto('/admin/legacy')
    await expect(page.getByRole('heading', { name: 'Formal operations' })).toBeVisible()
    await page.getByLabel('Subject', { exact: true }).fill('Synthetic')
    await page.getByLabel('Recorded state').selectOption('pending')
    await page.getByRole('button', { name: 'Apply filters' }).click()
    await expect(page).toHaveURL(/search=Synthetic/)
    await expect(page).toHaveURL(/state=pending/)
    await page.screenshot({ path: `output/playwright/admin-console/read-fixtures/formal-list-${info.project.name}-synthetic.png`, fullPage: true })
    await page.getByRole('link', { name: /next.*page/i }).click()
    await expect(page.getByText('Synthetic privacy request next page', { exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: /next.*page/i })).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
test('formal details show stored markup as text with no operational controls', async ({ page }, info) => {
    await page.goto('/admin/legacy/grievances/55555555-5555-4555-8555-555555555555')
    await expect(page.getByRole('heading', { name: 'Request as recorded' })).toBeVisible()
    await expect(page.getByText('<script>window.legacyLeak=true</script> Synthetic text remains text.', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => Reflect.get(window, 'legacyLeak'))).toBeUndefined()
    await expect(page.getByRole('button', { name: /resolve|lockdown|export|send|sign/i })).toHaveCount(0)
    await expect(page.getByLabel('Formal record limits')).toContainText('Read-only review')
    await page.screenshot({ path: `output/playwright/admin-console/read-fixtures/formal-detail-${info.project.name}-synthetic.png`, fullPage: true })
})
