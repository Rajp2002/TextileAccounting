test('a confirmed save disables new mutations until refreshed detail reaches its committed version', async ({ page }) => {
    let detailReads = 0, release: () => void = () => undefined
    const gate = new Promise<void>(resolve => { release = resolve })
    await page.route('**/__formal_fixture__/detail?kind=privacy', async route => {
        if (++detailReads === 2) await gate
        await route.continue()
    })
    await go(page, privacyPath); await readyUpdate(page)
    await page.getByRole('button', { name: 'Save case update', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Saved to the case. No message was sent.' })).toBeVisible()
    await expect(page.getByTestId('synthetic-current-version')).toHaveText('Synthetic server version 1')
    await expect(page.getByLabel('Next action', { exact: true })).toBeDisabled()
    await expect(page.getByLabel(/^Private note/)).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Save case update', exact: true })).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Add private note', exact: true })).toBeDisabled()
    expect((await attempts(page)).items).toHaveLength(1)
    release()
    await expect(page.getByTestId('synthetic-current-version')).toHaveText('Synthetic server version 2')
    await expect(page.getByRole('button', { name: 'Save case update', exact: true })).toBeEnabled()
    await readyUpdate(page)
    await page.getByLabel('Next action', { exact: true }).fill('Second synthetic action after refreshed confirmation')
    await page.getByRole('button', { name: 'Save case update', exact: true }).click()
    await expect(page.getByTestId('synthetic-current-version')).toHaveText('Synthetic server version 3')
    const sent = await attempts(page)
    expect(sent.items).toHaveLength(2); expect(sent.committedCount).toBe(2)
    expect(sent.items[1].payload).toMatchObject({ expectedVersion: 2, nextAction: 'Second synthetic action after refreshed confirmation' })
})

