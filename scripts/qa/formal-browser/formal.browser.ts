import { randomUUID } from 'node:crypto'
import { expect, test, type Page } from '@playwright/test'
import { fixtureId } from './fixture-data'

type Attempt = { path: string; payload: Record<string, unknown> }
type Attempts = { items: Attempt[]; committedCount: number }
const privacyPath = `/admin/formal/privacy/${fixtureId}`, securityPath = `/admin/formal/security/${fixtureId}`
test.beforeEach(async ({ page, context }) => {
    await context.addCookies([{ name: 'synthetic-formal-session', value: randomUUID(), url: 'http://127.0.0.1:4190' }])
    await page.route('**/*', route => ['127.0.0.1', 'localhost', '::1'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
    await page.request.post('/__formal_fixture__/reset', { data: {} })
})
async function attempts(page: Page): Promise<Attempts> { return (await page.request.get('/__formal_fixture__/attempts')).json() }
async function scenario(page: Page, steps: string[]) { await page.request.post('/__formal_fixture__/scenario', { data: { steps } }) }
async function go(page: Page, path: string) {
    await page.goto(path, { waitUntil: 'domcontentloaded' })
    await expect(page.getByText('Synthetic component fixtures — no authentication or production-data verification', { exact: true })).toBeVisible()
    if (path === privacyPath || path === securityPath) await expect(page.getByRole('heading', { name: path === privacyPath ? 'Synthetic privacy request' : 'Synthetic security incident', exact: true })).toBeVisible()
}
async function noOverflow(page: Page) { expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true) }
async function fillIntake(page: Page) {
    await page.getByLabel('Subject', { exact: true }).fill('Synthetic received privacy request')
    await page.getByLabel(/^Received context/).fill('Synthetic context received by email. No actual customer request.')
    await page.getByLabel('Received at (UTC)', { exact: true }).fill('2026-10-04T12:00')
    await page.getByLabel(/^Original channel reference/).fill('fixture-received-message')
    await page.getByLabel('Next action', { exact: true }).fill('Verify authority through the existing channel')
    await page.getByLabel('Internal follow-up due (UTC)', { exact: true }).fill('2026-10-05T12:00')
}
async function readyUpdate(page: Page) {
    await page.getByLabel('Next action', { exact: true }).fill('Original synthetic case draft action')
    await page.getByLabel('Reason for change (private)', { exact: true }).fill('Synthetic founder review')
}

test('manual intake records receipt without claiming acknowledgement or delivery', async ({ page }) => {
    await go(page, '/admin/formal/new')
    await expect(page.getByText(/Intake does not send an acknowledgement or verify/)).toBeVisible()
    await expect(page.getByText('Stored for founder case handling. Nothing is sent to the contact.')).toBeVisible()
    await fillIntake(page)
    await page.getByRole('button', { name: 'Record case', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Synthetic received privacy request', exact: true })).toBeVisible()
    const sent = await attempts(page)
    expect(sent.committedCount).toBe(1)
    expect(sent.items[0]).toMatchObject({ path: '/api/admin/formal', payload: { kind: 'privacy', source: 'manual_email', orgId: null, requesterUserId: null } })
    expect(sent.items[0].payload).not.toHaveProperty('acknowledgedAt')
    await expect(page.getByRole('button', { name: /send|notify|disclose|delete|lockdown/i })).toHaveCount(0)
    await noOverflow(page)
})

