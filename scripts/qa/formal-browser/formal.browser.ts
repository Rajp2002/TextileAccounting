test('lost committed response then 429 retries the same original request UUID and payload', async ({ page }) => {
    await scenario(page, ['commit_lost', 'throttle', 'success'])
    await go(page, privacyPath); await readyUpdate(page)
    await page.getByRole('button', { name: 'Save case update', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Retry original save', exact: true })).toBeVisible()
    expect((await attempts(page)).committedCount).toBe(1)
    await page.getByRole('button', { name: 'Retry original save', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('Synthetic throttled retry')
    await page.getByRole('button', { name: 'Retry original save', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: 'Saved to the case. No message was sent.' })).toBeVisible()
    const sent = await attempts(page)
    expect(sent.items).toHaveLength(3); expect(sent.committedCount).toBe(1)
    expect(sent.items[1]).toEqual(sent.items[0]); expect(sent.items[2]).toEqual(sent.items[0])
    expect(sent.items[0].payload.clientRequestId).toMatch(/^[0-9a-f-]{36}$/)
})

