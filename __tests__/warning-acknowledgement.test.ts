import { describe, expect, it } from 'vitest'
import { warningAcknowledgementKey } from '@/lib/warning-acknowledgement'
import { validateEstimatorSnapshot } from '@/lib/estimator-validation'
import { makeFreeDemo } from '@/lib/free-estimator-defaults'

const estimate = makeFreeDemo()
const withWarpRate = (rate: number) => ({ ...estimate, warpRows: estimate.warpRows.map((row, index) => index === 0 ? { ...row, yarnRate: rate } : row) })
const keyFor = (state: ReturnType<typeof makeFreeDemo>) =>
  warningAcknowledgementKey(validateEstimatorSnapshot(state, { requireTapeLength: false }).warnings ?? [], state)

describe('warningAcknowledgementKey', () => {
  it('is empty when there is nothing to review', () => {
    expect(warningAcknowledgementKey([], estimate)).toBe('')
  })

  it('changes when a warned value changes, even if the warning text is identical', () => {
    const reviewed = withWarpRate(1001)
    const changed = withWarpRate(2000)
    const warnings = (state: typeof reviewed) => (validateEstimatorSnapshot(state, { requireTapeLength: false }).warnings ?? [])
      .map(({ field, message }) => ({ field, message }))
    // Same field and message for both rates: the old key could be reused.
    expect(warnings(changed)).toEqual(warnings(reviewed))
    expect(warnings(reviewed).length).toBeGreaterThan(0)
    expect(keyFor(changed)).not.toBe(keyFor(reviewed))
  })

  it('changes after any other effective input edit while the warning stands', () => {
    const reviewed = withWarpRate(1001)
    expect(keyFor({ ...reviewed, profitPct: reviewed.profitPct + 1 })).not.toBe(keyFor(reviewed))
  })

  it('survives representation-only changes that leave the reviewed inputs and warning text alone', () => {
    const reviewed = withWarpRate(1001)
    // Row ids are regenerated by restores and templates; they are not inputs.
    const reidentified = { ...reviewed, warpRows: reviewed.warpRows.map(row => ({ ...row, id: `${row.id}-new` })) }
    expect(keyFor(reidentified)).toBe(keyFor(reviewed))
  })
})

describe('the estimator binds approval to the reviewed inputs', () => {
  it('derives the acknowledged key from the warnings and the current inputs, for Free and paid saves alike', async () => {
    const { readFileSync } = await import('node:fs')
    const estimator = readFileSync('app/(dashboard)/owner/estimator/EstimatorClient.tsx', 'utf8')
    const key = estimator.slice(estimator.indexOf('const warningKey = useMemo('), estimator.indexOf('const warningsAcknowledged'))
    expect(key).toContain('warningAcknowledgementKey(estimatorWarnings, state)')
    expect(key).not.toContain('`${warning.field}:${warning.message}`')
  })
})
