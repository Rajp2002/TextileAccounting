const html = (props: Partial<React.ComponentProps<typeof ChallanPrint>> = {}) =>
    renderToStaticMarkup(<ChallanPrint d={challan} businessName="Shree Weaves" {...props} />)
const count = (haystack: string, needle: string) => haystack.split(needle).length - 1

describe('branded delivery challan print', () => {
    it('heads each of the three labelled copies with the Weavly mark, the factory name and the challan number', () => {
        const page = html()
        expect(count(page, '<article class="challan-copy"')).toBe(3)
        expect(count(page, `src="${WEAVLY_LOGO_DATA_URI}"`)).toBe(3)
        expect(count(page, 'alt="Weavly"')).toBe(3)
        expect(count(page, '<div class="issuername">Shree Weaves</div>')).toBe(3)
        expect(count(page, 'DC-2026-0042')).toBe(3)
        for (const copy of ['Original — Consignee', 'Duplicate — Transporter', 'Triplicate — Consignor'])
            expect(count(page, `<span class="copytag">${copy}</span>`)).toBe(1)
        expect(count(page, 'Generated by Weavly')).toBe(3)
    })

    it('uses the consignor name when the factory name is blank or missing, and escapes whatever it prints', () => {
        for (const businessName of [undefined, '', '   '])
            expect(html({ businessName })).toContain('<div class="issuername">Shree Weaves Pvt Ltd</div>')
        const hostile = html({ businessName: '<script>alert(1)</script>' })
        expect(hostile).not.toContain('<script>alert(1)</script>')
        expect(hostile).toContain('&lt;script&gt;')
    })

    it('keeps every particular the delivery record is required to carry', () => {
        const page = html()
        for (const text of [
            'Consignor / Sender',
            'Consignee / Customer',
            'GSTIN: 24ABCDE1234F1Z5',
            'Ambika Textiles',
            'Godown 4, Sahara Darwaja',
            '60x60 Poplin',
            'Rs 40.00 / m',
            '0101',
            '225.00',
            '275.50',
            '2 lots — Total sent',
            '500.50 m',
            'Rs 20020.00',
            'Handle with care',
            'Recipient signature / stamp',
            'Authorized sender signature',
            'For Shree Weaves Pvt Ltd',
        ])
            expect(page).toContain(text)
        expect(page).toContain('Not entered — refer to applicable invoice')
    })

    it('marks drafts and reversals so they cannot pass as issued', () => {
        expect(html({ d: { ...challan, delivery_status: 'draft' } })).toContain('DRAFT — NOT ISSUED')
        expect(html({ d: { ...challan, delivery_status: 'reversed' } })).toContain('REVERSED — SEE HISTORY')
        expect(html()).toContain('>ISSUED<')
    })

    it('keeps the print rules: only the document prints, each copy on its own page, brand colours kept', () => {
        const page = html()
        expect(page).toContain('@page { size: A4; margin: 14mm; }')
        expect(page).toContain('.no-print,.no-print * { display:none!important; }')
        expect(page).toContain('.challan-copy { break-after:page;')
        expect(page).toContain('thead { display:table-header-group; }')
        expect(page).toContain('print-color-adjust:exact')
        expect(page).toContain('background:#18252E')
        expect(page).toContain('background:#E27025')
    })
})

describe('printing from the draft editor', () => {
    const editor = read('app/(dashboard)/owner/dispatches/ChallanDraftEditor.tsx')
    const client = read('app/(dashboard)/owner/dispatches/ChallansClient.tsx')

    it('enables Print only when the draft is printable, and says what is missing otherwise', () => {
        expect(editor).toContain('const readiness = challanPrintReadiness(draft)')
        expect(editor).toContain('disabled={disabled || !readiness.ready}')
        expect(editor).toContain('onClick={() => onSavePrint(prepareChallanDraft(draft))}')
        expect(editor).toContain("t('challan.printNeeds'")
        expect(editor).toContain('readiness.missing.map(tx)')
        expect(editor).toMatch(/aria-describedby=\{\s*readiness\.ready \? undefined : 'challan-print-hint'\s*\}/)
    })

    it('shares the required-field list with the readiness check instead of keeping its own', () => {
        expect(editor).toContain('REQUIRED_CHALLAN_DOCUMENT_FIELDS')
        expect(editor).not.toMatch(/const required = \[/)
    })

    it('saves before printing, opens the tab inside the click, and never leaves a blank tab behind', () => {
        expect(client).toContain('onSavePrint={savePrint}')
        expect(client).toContain("window.open('', '_blank')")
        expect(client).toContain('tab.opener = null')
        expect(client).toContain('isSameChallanDraft(value, selected)')
        expect(client).toContain("await save('save', value, openPrint)")
        expect(client).toContain('tab?.close()')
        expect(client).toContain("tx('printBlocked')")
        expect(client).toMatch(/if \(tourSample \|\| lock\.current \|\| pending\) return/)
    })

    it('opens the print page the moment the server confirms the save, not after the lists reload', () => {
        const save = client.slice(client.indexOf('async function save('), client.indexOf('async function savePrint('))
        expect(save.indexOf('onSaved?.(result.id)')).toBeGreaterThan(0)
        expect(save.indexOf('onSaved?.(result.id)')).toBeLessThan(save.indexOf('await view(result.id)'))
        expect(save.indexOf('onSaved?.(result.id)')).toBeLessThan(save.indexOf('await load()'))
    })

    it('has the Save & print strings in every language, in native script with the item token kept', () => {
        for (const [name, locale] of Object.entries({ en, hi, gu })) {
            const copy = locale.challan as Record<string, string>
            for (const key of ['saveAndPrint', 'printNeeds', 'printBlocked'])
                expect(copy[key], `${name}.${key}`).toBeTruthy()
            expect(copy.printNeeds).toContain('{items}')
            if (name !== 'en')
                for (const key of ['saveAndPrint', 'printNeeds', 'printBlocked'])
                    expect(copy[key].replace(/\{items\}|PDF/g, '')).toMatch(
                        name === 'gu' ? /[઀-૿]/ : /[ऀ-ॿ]/,
                    )
        }
    })
})
